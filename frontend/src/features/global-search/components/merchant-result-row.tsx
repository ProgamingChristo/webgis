"use client";

import Image from "next/image";
import { ChevronRight, Footprints, MapPin, Store, Tag } from "lucide-react";
import { useEffect, useState } from "react";
import type { Merchant } from "@/types/getra";
import { useAdImpression, type SponsoredPinDTO } from "@/src/features/umkm-advertising";

import { merchantPrice, merchantDistance, merchantPhoto, merchantOpening, merchantSpatialContext } from "../merchant-presentation";
export { merchantPrice, merchantDistance } from "../merchant-presentation";

type ResultReasonOptions = {
  budget?: number;
  rank?: number;
  sort?: "RELEVANCE" | "NEAREST" | "PRICE_ASC";
};

function compactRupiah(amount: number) {
  if (amount >= 1_000_000) return `Rp${Number((amount / 1_000_000).toFixed(1))}jt`;
  if (amount >= 1_000) return `Rp${Number((amount / 1_000).toFixed(1))}rb`;
  return `Rp${amount}`;
}

/** Deterministic evidence only; this must never be generated by the LLM. */
export function merchantResultReasons(merchant: Merchant, options: ResultReasonOptions = {}) {
  const reasons: string[] = [];
  const distance = merchant.networkRouteStatus === "ROUTABLE" && Number.isFinite(merchant.networkDistanceMeters)
    ? merchant.networkDistanceMeters ?? null
    : merchant.referenceDistance?.meters ?? null;
  const walkingMinutes = merchant.networkRouteStatus === "ROUTABLE" && Number.isFinite(merchant.networkDurationSeconds)
    ? Math.ceil((merchant.networkDurationSeconds ?? 0) / 60)
    : null;
  const validBudget = typeof options.budget === "number" && Number.isFinite(options.budget) && options.budget > 0
    ? options.budget
    : null;
  const validPrice = typeof merchant.observedPriceAmount === "number" && Number.isFinite(merchant.observedPriceAmount) && merchant.observedPriceAmount > 0
    ? merchant.observedPriceAmount
    : null;

  if (options.rank === 1 && options.sort === "NEAREST" && distance !== null) {
    reasons.push(`Paling dekat · ${distance < 1_000 ? `${Math.round(distance)} m` : `${(distance / 1_000).toLocaleString("id-ID", { maximumFractionDigits: 1 })} km`}`);
  } else if (walkingMinutes !== null) {
    reasons.push(`${walkingMinutes} menit jalan kaki`);
  } else if (distance !== null) {
    reasons.push(`${distance < 1_000 ? `${Math.round(distance)} m` : `${(distance / 1_000).toLocaleString("id-ID", { maximumFractionDigits: 1 })} km`} dari titik acuan`);
  }

  if (validBudget !== null && validPrice !== null && validPrice <= validBudget) {
    reasons.push(`Sesuai anggaran ≤ ${compactRupiah(validBudget)}`);
  } else if (merchant.openingStatus === "OPEN") {
    reasons.push("Buka sekarang");
  } else if (merchant.recommendation?.reasons.includes("FOOD_EXACT_MATCH")) {
    reasons.push("Kategori paling sesuai");
  } else if (merchant.recommendation?.reasons.includes("FOOD_MATCH")) {
    reasons.push("Kategori sesuai pencarian");
  }

  return reasons.slice(0, 2);
}

export function MerchantResultRow({ merchant, selected, onSelect, budget, sponsored = false, sponsoredPlacement, rank, sort = "RELEVANCE" }: {
  merchant: Merchant;
  selected: boolean;
  onSelect: (merchant: Merchant) => void;
  budget?: number;
  sponsored?: boolean;
  sponsoredPlacement?: SponsoredPinDTO;
  rank?: number;
  sort?: "RELEVANCE" | "NEAREST" | "PRICE_ASC";
}) {
  const { ref } = useAdImpression<HTMLButtonElement>({
    campaignId: sponsoredPlacement?.campaign_id,
    creativeId: sponsoredPlacement?.creative_id,
    placement: "SPONSORED_PIN",
    surface: "COMMUTER_RESULT_LIST",
    enabled: Boolean(sponsoredPlacement),
  });
  const [failedPhoto, setFailedPhoto] = useState<string | null>(null);
  useEffect(() => {
    if (selected) ref.current?.scrollIntoView({ block: "nearest", behavior: "smooth" });
  }, [ref, selected]);
  const photo = merchant.photo !== failedPhoto ? merchantPhoto(merchant) : null;
  const distance = merchantDistance(merchant);
  const opening = merchantOpening(merchant);
  const inBudget = budget !== undefined && typeof merchant.observedPriceAmount === "number" && merchant.observedPriceAmount > 0 && merchant.observedPriceAmount <= budget;
  const reasons = merchantResultReasons(merchant, { budget, rank, sort });
  return <button ref={ref} type="button" className="commuter-merchant" aria-pressed={selected} onClick={() => onSelect(merchant)} data-merchant-id={merchant.id}>
    {rank ? <span className="commuter-merchant__rank" aria-label={`Peringkat ${rank}`}>{rank}</span> : null}
    <span className="commuter-merchant__photo">{photo ? <Image src={photo} alt="" width={72} height={88} unoptimized onError={() => setFailedPhoto(photo)} /> : <Store size={26} aria-label="Foto belum tersedia" />}</span>
    <span className="commuter-merchant__body">
      <strong>{merchant.name}</strong><span>{merchant.category || merchant.brand}</span>
      {!distance && merchantSpatialContext(merchant) ? <span className="commuter-merchant__meta">{merchantSpatialContext(merchant)}</span> : null}
      {distance ? <span className="commuter-merchant__meta"><Footprints size={12} />{distance}</span> : null}
      <span className="commuter-merchant__meta"><MapPin size={12} />{merchant.address || [merchant.district, merchant.city].filter(Boolean).join(", ") || "Alamat belum tersedia"}</span>
      <span className="commuter-merchant__meta"><Tag size={12} />{merchantPrice(merchant)}</span>
      <span className="commuter-badges">
        {sponsored ? <span data-status="SPONSORED">Promosi</span> : null}
        {opening !== "UNKNOWN" ? <span data-status={opening}>{opening === "OPEN" ? "Buka sekarang" : "Tutup"}</span> : null}
        {inBudget ? <span data-status="OPEN">Masuk anggaran</span> : null}
      </span>
      {reasons.length ? <span className="commuter-merchant__reasons">{reasons.join(" · ")}</span> : null}
    </span><ChevronRight size={16} />
  </button>;
}
